ALTER TABLE public.escaneos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.eventos ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Allow public read for authenticated users" ON public.generadores FOR SELECT TO authenticated USING (true);
CREATE POLICY "Allow public read for authenticated users" ON public.escaneos FOR SELECT TO authenticated USING (true);
CREATE POLICY "Allow public read for authenticated users" ON public.eventos FOR SELECT TO authenticated USING (true);

CREATE POLICY "Allow updates for authenticated users" ON public.generadores FOR UPDATE TO authenticated USING (true);
CREATE POLICY "Allow inserts for authenticated users" ON public.generadores FOR INSERT TO authenticated WITH CHECK (true);
CREATE POLICY "Allow deletes for authenticated users" ON public.generadores FOR DELETE TO authenticated USING (true);
CREATE POLICY "Allow inserts for authenticated users" ON public.escaneos FOR INSERT TO authenticated WITH CHECK (true);
