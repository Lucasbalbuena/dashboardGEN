-- TABLAS PRINCIPALES

-- 1. Generadores
CREATE TABLE IF NOT EXISTS public.generadores (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre TEXT NOT NULL,
    nodo TEXT NOT NULL,
    serial TEXT UNIQUE, -- Added UNIQUE constraint
    potencia NUMERIC, -- Changed to NUMERIC
    estado TEXT DEFAULT 'OFF',
    voltaje NUMERIC, -- Changed to NUMERIC
    corriente NUMERIC, -- Changed to NUMERIC
    frecuencia NUMERIC, -- Changed to NUMERIC
    combustible NUMERIC DEFAULT 0,
    bateria NUMERIC, -- Changed to NUMERIC
    horas_motor NUMERIC, -- Changed to NUMERIC
    alarmas TEXT[] DEFAULT '{}',
    ultima_lectura TIMESTAMPTZ DEFAULT NOW(),
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW() -- New column
);

-- 2. Escaneos
CREATE TABLE IF NOT EXISTS public.escaneos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    serial TEXT,
    texto_ocr TEXT,
    json_extraido JSONB,
    confianza NUMERIC,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Eventos
CREATE TABLE IF NOT EXISTS public.eventos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    serial TEXT,
    generador_nombre TEXT,
    operador TEXT,
    tipo TEXT NOT NULL,
    litros NUMERIC,
    nivel_resultante NUMERIC,
    metadata JSONB DEFAULT '{}',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- HABILITAR REALTIME
ALTER PUBLICATION supabase_realtime ADD TABLE generadores;
ALTER PUBLICATION supabase_realtime ADD TABLE escaneos;
ALTER PUBLICATION supabase_realtime ADD TABLE eventos;

